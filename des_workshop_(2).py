def remove_low_variance_genes(data, threshold=0.2):
    """
    Removes the least variant genes (e.g., 20%) based on variance.

    Parameters:
        data (pd.DataFrame): Gene expression data where rows are samples and columns are genes.
        threshold (float): Proportion of genes to remove based on lowest variance (default: 0.2).

    Returns:
        pd.DataFrame: Filtered DataFrame with the least variant genes removed.
    """
    # Calculate the variance of each gene (column)
    gene_variances = data.var()

    # Determine the number of genes to remove
    num_genes_to_remove = int(len(gene_variances) * threshold)

    # Identify the indices of genes with the lowest variance
    least_variant_genes = gene_variances.nsmallest(num_genes_to_remove).index

    # Remove the least variant genes from the data
    filtered_data = data.drop(columns=least_variant_genes)

    return filtered_data
